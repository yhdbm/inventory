# --- SECRET_KEY -------------------------------------------------------------
# Deliberately NOT stored in this file. The project lives on the network share
# \\fileserver\share, readable by anyone with share access — and sessions are
# signed with SECRET_KEY, so whoever can read the key can forge a session
# cookie, including one authenticating as a superuser. So the key is loaded
# from a machine-local location instead, and a missing key is a hard failure
# rather than a silent fall back to a default (which would defeat the point).
#
# Create it once per serving machine:  python manage.py init_secret_key
def _load_secret_key():
    key = os.environ.get('INVENTORY_SECRET_KEY')
    if key:
        return key
    # Same resolution the init_secret_key command uses.
    override = os.environ.get('INVENTORY_SECRET_KEY_FILE')
    if override:
        path = Path(override)
    else:
        path = Path(os.environ.get('PROGRAMDATA') or 'C:/ProgramData') / 'inventory' / 'secret_key'
    try:
        key = path.read_text(encoding='utf-8').strip()
    except OSError:
        raise ImproperlyConfigured(
            f'No Django SECRET_KEY found on this machine.\n'
            f'  Looked for: the INVENTORY_SECRET_KEY env var, then {path}\n'
            f'\n'
            f'FIX — from the project folder, run:\n'
            f'      python init_secret_key.py\n'
            f'\n'
            f'That is a STANDALONE script (not "manage.py init_secret_key") because\n'
            f'manage.py loads this settings file first, so any management command\n'
            f'would hit this very error before it could run.\n'
            f'\n'
            f'If another machine already serves this app and users should stay signed\n'
            f'in across both, COPY its key file here instead of generating a new one —\n'
            f'the value has to match.'
        )
    if not key:
        raise ImproperlyConfigured(f'The SECRET_KEY file {path} is empty.')
    return key


SECRET_KEY = _load_secret_key()

