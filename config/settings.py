# Sessions live in the database. (They used to be signed cookies, on the theory
# that the server might not be able to write the SQLite file on the share — but
# AccessLogMiddleware already writes a row on every page view, so DB writes are
# not a new failure mode here. The important difference: a DB session key is
# random, so leaking SECRET_KEY no longer lets anyone mint a valid session.)
# SESSION_SAVE_EVERY_REQUEST stays at its False default, so this is one write
# per login rather than one per request.
