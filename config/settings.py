# Left False on purpose: the app is served over plain HTTP on the LAN, so
# marking the cookies Secure would stop them being sent at all. Consequence to
# be aware of — passwords and session cookies cross the network in cleartext.
# Putting a TLS-terminating reverse proxy in front of this is the real fix.
